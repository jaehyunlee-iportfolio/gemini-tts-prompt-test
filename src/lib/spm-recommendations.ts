/**
 * VP(bundleName)별 레벨(beginner/intermediate/advanced) SPM 추천값 (최종).
 *
 * 방식(사용자 확정): 고정 간격(beginner->intermediate 25, intermediate->advanced 35 SPM)을
 * 전 VP 공통 적용하되, beginner 앵커를 다음과 같이 잡음:
 *  - GEMINI: 자연속도(rate 1.0 = baseSpm) 앵커. B = base-25, I = base, A = base+35.
 *    (자연 tempo가 이미 7-9세대라 그대로. 저rate 침묵 회피)
 *  - 비-GEMINI(Azure/GCP/AWS/CHIRP): 보수적 clean floor 0.6 앵커. B = round(base x0.6),
 *    I = B+25, A = B+60. (자연이 빨라 최대한 느리게. 0.6은 전 비-GEMINI가 기계음 없는
 *    가장 안전한 floor - AWS-Justin이 0.55 밑에서 붕괴해 이를 보호하는 값)
 * beginner/intermediate/advanced = API 요청 spm.
 *
 * 기계음 자동 검증: DNSMOS(무참조 MOS, scripts/spm_floor_find.py)로 rate별 SIG 측정.
 *   비-GEMINI는 rate 0.45까지 SIG 평평(AWS-Justin만 0.55 밑 붕괴). 최종 rate대(0.6~1.24)는
 *   전 VP clean. 단 사람 청감 최종 확정(임계값 캘리브레이션)은 별도.
 * *Wpm = rate 1.0 실측 자연속도 x rate 환산(추정). category: child(beginner<=150WPM)/fast.
 * TC(Typecast) 3종은 v2 미지원.
 */

